#!/usr/bin/env python3
"""Dump the live FastAPI schema to packages/contracts/openapi.yaml.

The spec is generated, never hand-edited: the app is the source of truth for
the contract, so regenerate after changing any route or schema and commit the
result alongside the change.

    cd apps/api && poetry run python scripts/export_openapi.py
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.main import app  # noqa: E402

DEFAULT_OUT = Path(__file__).resolve().parents[3] / "packages" / "contracts" / "openapi.yaml"

HEADER = """# Generated by apps/api/scripts/export_openapi.py -- do not edit by hand.
# Regenerate with: cd apps/api && poetry run python scripts/export_openapi.py
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="destination yaml file")
    parser.add_argument("--check", action="store_true", help="exit non-zero if the file is stale")
    args = parser.parse_args()

    spec = app.openapi()
    rendered = HEADER + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True)

    if args.check:
        if not args.out.exists():
            print(f"❌ {args.out} does not exist; run without --check to generate it.")
            return 1
        if args.out.read_text(encoding="utf-8") != rendered:
            print(f"❌ {args.out} is stale. Regenerate with:")
            print("   cd apps/api && poetry run python scripts/export_openapi.py")
            return 1
        print(f"✅ {args.out} is up to date.")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rendered, encoding="utf-8")
    paths = len(spec.get("paths", {}))
    schemas = len(spec.get("components", {}).get("schemas", {}))
    print(f"✅ Wrote {args.out} ({paths} paths, {schemas} schemas)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
